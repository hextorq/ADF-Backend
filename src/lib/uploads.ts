import crypto from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { env } from "../env.js";

const MB = 1024 * 1024;

const IMAGE_EXTENSIONS = [".jpg", ".jpeg", ".png", ".webp", ".gif"];
const DOCUMENT_EXTENSIONS = [".pdf", ".doc", ".docx", ".txt", ...IMAGE_EXTENSIONS];

interface FolderRules {
  /** Public author-facing folders can be written without an admin token. */
  public: boolean;
  /** Internal folders (generated output) are not exposed through the HTTP upload endpoint. */
  http: boolean;
  maxBytes: number;
  extensions: string[];
}

/**
 * Every uploaded file lives under <backend>/uploads/<folder>/<file>.
 * The folder is the only thing the caller has to choose, and it is always
 * validated against this map — no arbitrary directories can be created.
 */
export const UPLOAD_FOLDERS = {
  // --- public author submissions ---
  manuscripts: { public: true, http: true, maxBytes: 50 * MB, extensions: DOCUMENT_EXTENSIONS },
  chapters: { public: true, http: true, maxBytes: 50 * MB, extensions: DOCUMENT_EXTENSIONS },
  covers: { public: true, http: true, maxBytes: 10 * MB, extensions: IMAGE_EXTENSIONS },
  "author-photos": { public: true, http: true, maxBytes: 10 * MB, extensions: IMAGE_EXTENSIONS },
  payments: { public: true, http: true, maxBytes: 10 * MB, extensions: IMAGE_EXTENSIONS },

  // --- admin managed content ---
  // NOTE: the `public` flags are intentionally open right now. Flip them back to
  // false to require an admin token again — nothing else has to change.
  publications: { public: true, http: true, maxBytes: 50 * MB, extensions: DOCUMENT_EXTENSIONS },
  books: { public: true, http: true, maxBytes: 10 * MB, extensions: IMAGE_EXTENSIONS },
  authors: { public: true, http: true, maxBytes: 10 * MB, extensions: IMAGE_EXTENSIONS },
  cms: { public: true, http: true, maxBytes: 10 * MB, extensions: IMAGE_EXTENSIONS },
  templates: { public: true, http: true, maxBytes: 50 * MB, extensions: [".docx"] },
  misc: { public: true, http: true, maxBytes: 50 * MB, extensions: DOCUMENT_EXTENSIONS },

  // --- generated by the server, never uploaded directly ---
  formatted: { public: false, http: false, maxBytes: 50 * MB, extensions: [".docx"] },
} satisfies Record<string, FolderRules>;

export type UploadFolder = keyof typeof UPLOAD_FOLDERS;

/**
 * Resolved once, deterministically:
 *   src/lib  -> backend/uploads
 *   dist/lib -> backend/uploads
 * UPLOADS_DIR can override it for deployments.
 */
export const UPLOADS_ROOT = env.UPLOADS_DIR
  ? path.resolve(env.UPLOADS_DIR)
  : path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../../uploads");

const MIME_BY_EXT: Record<string, string> = {
  ".jpg": "image/jpeg",
  ".jpeg": "image/jpeg",
  ".png": "image/png",
  ".webp": "image/webp",
  ".gif": "image/gif",
  ".pdf": "application/pdf",
  ".doc": "application/msword",
  ".docx": "application/vnd.openxmlformats-officedocument.wordprocessingml.document",
  ".txt": "text/plain; charset=utf-8",
};

export class UploadError extends Error {
  constructor(message: string) {
    super(message);
    this.name = "UploadError";
  }
}

export interface SavedUpload {
  /** Public URL, safe to store in Postgres and render in the browser. */
  url: string;
  /** Path on the server, relative to the backend root. */
  path: string;
  folder: UploadFolder;
  filename: string;
  size: number;
  mimetype: string;
}

export function isUploadFolder(value: string): value is UploadFolder {
  return Object.prototype.hasOwnProperty.call(UPLOAD_FOLDERS, value);
}

export function getFolderRules(folder: UploadFolder): FolderRules {
  return UPLOAD_FOLDERS[folder];
}

export function isPublicFolder(folder: UploadFolder): boolean {
  return UPLOAD_FOLDERS[folder].public;
}

export function listHttpFolders(includeAdmin: boolean) {
  return (Object.keys(UPLOAD_FOLDERS) as UploadFolder[])
    .filter((folder) => UPLOAD_FOLDERS[folder].http)
    .filter((folder) => includeAdmin || UPLOAD_FOLDERS[folder].public)
    .map((folder) => ({
      folder,
      public: UPLOAD_FOLDERS[folder].public,
      maxBytes: UPLOAD_FOLDERS[folder].maxBytes,
      extensions: UPLOAD_FOLDERS[folder].extensions,
    }));
}

export function ensureUploadsRoot(): void {
  fs.mkdirSync(UPLOADS_ROOT, { recursive: true });
}

function sanitizeBaseName(originalname: string): string {
  const parsed = path.parse(originalname || "file");
  const base = parsed.name
    .normalize("NFKD")
    .replace(/[^\w.-]+/g, "-")
    .replace(/[-_.]{2,}/g, "-")
    .replace(/^[-_.]+|[-_.]+$/g, "")
    .slice(0, 60);
  return base || "file";
}

function extensionOf(originalname: string): string {
  return path.extname(originalname || "").toLowerCase();
}

function assertAllowedExtension(folder: UploadFolder, originalname: string): string {
  const ext = extensionOf(originalname);
  if (!ext || !UPLOAD_FOLDERS[folder].extensions.includes(ext)) {
    const allowed = UPLOAD_FOLDERS[folder].extensions.join(", ");
    throw new UploadError(
      `File type "${ext || "unknown"}" is not allowed in "${folder}". Allowed: ${allowed}`
    );
  }
  return ext;
}

function buildFilename(folder: UploadFolder, originalname: string, ext: string): string {
  const unique = `${Date.now()}-${crypto.randomBytes(4).toString("hex")}`;
  return `${sanitizeBaseName(originalname)}-${unique}${ext}`;
}

function assertInsideRoot(target: string): void {
  const relative = path.relative(UPLOADS_ROOT, target);
  if (relative.startsWith("..") || path.isAbsolute(relative)) {
    throw new UploadError("Resolved upload path escapes the uploads directory");
  }
}

function describe(folder: UploadFolder, filename: string, size: number): SavedUpload {
  return {
    url: `/uploads/${folder}/${filename}`,
    path: path.posix.join("uploads", folder, filename),
    folder,
    filename,
    size,
    mimetype: MIME_BY_EXT[extensionOf(filename)] || "application/octet-stream",
  };
}

/**
 * Writes an uploaded buffer into uploads/<folder>/ and returns the path to store in the DB.
 */
export async function saveUpload(
  file: Express.Multer.File,
  folder: UploadFolder
): Promise<SavedUpload> {
  if (!file || !file.buffer || file.buffer.length === 0) {
    throw new UploadError("Uploaded file is empty");
  }

  const rules = UPLOAD_FOLDERS[folder];
  if (file.size > rules.maxBytes) {
    throw new UploadError(
      `File is too large for "${folder}" (max ${Math.round(rules.maxBytes / MB)} MB)`
    );
  }

  const ext = assertAllowedExtension(folder, file.originalname);
  const filename = buildFilename(folder, file.originalname, ext);
  const dir = path.join(UPLOADS_ROOT, folder);
  const target = path.join(dir, filename);
  assertInsideRoot(target);

  await fs.promises.mkdir(dir, { recursive: true });
  await fs.promises.writeFile(target, file.buffer);

  return describe(folder, filename, file.buffer.length);
}

/**
 * Writes a server-generated file (e.g. the formatted DOCX) into uploads/<folder>/.
 */
export async function saveBuffer(
  buffer: Buffer,
  originalname: string,
  folder: UploadFolder
): Promise<SavedUpload> {
  if (!buffer || buffer.length === 0) {
    throw new UploadError("Generated file is empty");
  }

  const ext = assertAllowedExtension(folder, originalname);
  const filename = buildFilename(folder, originalname, ext);
  const dir = path.join(UPLOADS_ROOT, folder);
  const target = path.join(dir, filename);
  assertInsideRoot(target);

  await fs.promises.mkdir(dir, { recursive: true });
  await fs.promises.writeFile(target, buffer);

  return describe(folder, filename, buffer.length);
}

/** Absolute path for a stored /uploads/... URL, or null when it is not one of ours. */
export function absolutePathForUploadUrl(url: string): string | null {
  if (!url || !url.startsWith("/uploads/")) return null;

  const segments = url.slice("/uploads/".length).split("/").filter(Boolean);
  if (segments.length === 0 || segments.some((segment) => segment === ".." || segment.includes("\\"))) {
    return null;
  }

  const target = path.join(UPLOADS_ROOT, ...segments);
  const relative = path.relative(UPLOADS_ROOT, target);
  if (relative.startsWith("..") || path.isAbsolute(relative)) return null;

  return target;
}

/**
 * Legacy support for /api/files/:id — looks for the blob on disk in the root
 * and in every one-level subfolder (new layout).
 */
export function findLocalUpload(id: string): string | null {
  if (!id || id.includes("..") || id.includes("/") || id.includes("\\")) return null;

  const direct = path.join(UPLOADS_ROOT, id);
  if (isFile(direct)) return direct;

  let entries: fs.Dirent[] = [];
  try {
    entries = fs.readdirSync(UPLOADS_ROOT, { withFileTypes: true });
  } catch {
    return null;
  }

  for (const entry of entries) {
    if (!entry.isDirectory()) continue;
    const candidate = path.join(UPLOADS_ROOT, entry.name, id);
    if (isFile(candidate)) return candidate;
  }

  return null;
}

function isFile(candidate: string): boolean {
  try {
    return fs.statSync(candidate).isFile();
  } catch {
    return false;
  }
}

/**
 * Maps an old /api/files/<id> blob name to the folder it belongs in.
 * The field prefix in the generated name tells us where it came from.
 */
export function folderForLegacyFilename(id: string): UploadFolder {
  const name = id.toLowerCase();

  if (name.startsWith("formatted-manuscript-")) return "formatted";
  if (name.startsWith("template-")) return "templates";
  if (name.startsWith("payment_screenshot-") || name.startsWith("payment-screenshot-")) return "payments";
  if (name.startsWith("cover_image-")) return "publications";
  if (name.startsWith("pdf_file-")) return "publications";
  if (name.startsWith("coverimage-")) return "covers";
  if (name.startsWith("authorphoto-") || name.startsWith("author_photo-")) return "author-photos";
  if (name.startsWith("manuscript-")) return "manuscripts";
  if (name.startsWith("image-")) return "cms";

  return "misc";
}

export function mimeForFilename(filename: string): string | null {
  return MIME_BY_EXT[extensionOf(filename)] || null;
}